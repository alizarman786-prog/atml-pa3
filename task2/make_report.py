"""Task 2 figures and tables from train_vlm.py outputs.
Usage: python make_report.py --run 196=DIR [--run 49=DIR] --out DIR
Writes fig_train_loss.png, fig_dev_curves.png, tables.md, qualitative.md.
"""
import json, argparse, os, random
import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

ap = argparse.ArgumentParser()
ap.add_argument('--run', action='append', required=True)
ap.add_argument('--out', required=True)
args = ap.parse_args()
os.makedirs(args.out, exist_ok=True)
RUNS = dict(r.split('=', 1) for r in args.run)
COL = ['#2a78d6', '#eb6834', '#1baf7a', '#eda100']
INK, INK2 = '#0b0b0b', '#52514e'
plt.rcParams.update({'font.size': 9, 'axes.edgecolor': INK2, 'axes.labelcolor': INK, 'xtick.color': INK2,
                     'ytick.color': INK2, 'axes.spines.top': False, 'axes.spines.right': False,
                     'axes.grid': True, 'grid.color': '#e6e5e0', 'grid.linewidth': 0.6, 'lines.linewidth': 2})


def jl(p):
    return [json.loads(l) for l in open(p)] if os.path.exists(p) else []


L = {k: jl(f'{d}/train_log.jsonl') for k, d in RUNS.items()}
DV = {k: jl(f'{d}/dev_eval.jsonl') for k, d in RUNS.items()}
FE = {k: json.load(open(f'{d}/final_eval.json')) for k, d in RUNS.items() if os.path.exists(f'{d}/final_eval.json')}
SM = {k: json.load(open(f'{d}/summary.json')) for k, d in RUNS.items() if os.path.exists(f'{d}/summary.json')}
PE = {k: jl(f'{d}/final_per_example.jsonl') for k, d in RUNS.items()}
BOUNDS = [2250, 3750]


def stage_lines(ax):
    for b in BOUNDS:
        ax.axvline(b, color=INK2, lw=0.8, ls=':')


# ---- training loss (EMA over updates)
fig, ax = plt.subplots(figsize=(7, 3.2))
for i, (k, log) in enumerate(L.items()):
    if not log:
        continue
    u = np.array([r['update'] for r in log]); y = np.array([r['loss'] for r in log])
    ema = np.zeros_like(y); m = y[0]
    for j, v in enumerate(y):
        m = 0.98 * m + 0.02 * v; ema[j] = m
    ax.plot(u, y, color=COL[i], alpha=0.15, lw=0.6)
    ax.plot(u, ema, color=COL[i], label=f'{k} visual tokens (EMA 0.98)')
stage_lines(ax)
for x, t in [(1125, 'caption'), (3000, 'visual instruction'), (4125, 'natural VQA')]:
    ax.text(x, 1.0, t, transform=ax.get_xaxis_transform(), ha='center', va='bottom', color=INK2, fontsize=8)
ax.set_xlabel('optimizer update'); ax.set_ylabel('training loss (mean per-example NLL)')
ax.legend(frameon=False)
fig.tight_layout(); fig.savefig(f'{args.out}/fig_train_loss.png', dpi=160); plt.close(fig)

# ---- dev curves
panels = [('caption_ref_loss', 'caption dev loss'),
          ('grounding_dev_swap_penalty', 'grounding dev: swap penalty\n(NLL complementary - correct)'),
          ('vqa_dev_swap_penalty', 'VQA dev: swap penalty\n(NLL complementary - correct)'),
          ('grounding_dev_noimage_penalty', 'grounding dev: no-image penalty'),
          ('vqa_dev_noimage_penalty', 'VQA dev: no-image penalty'),
          ('vqa_dev_nll_correct', 'VQA dev: answer NLL (correct image)')]
fig, axs = plt.subplots(2, 3, figsize=(10, 5.6))
for ax, (key, title) in zip(axs.flat, panels):
    for i, (k, dv) in enumerate(DV.items()):
        if dv:
            ax.plot([r['update'] for r in dv], [r[key] for r in dv], color=COL[i], marker='o', ms=3.5, label=f'{k} tokens')
    stage_lines(ax)
    if 'penalty' in key:
        ax.axhline(0, color=INK2, lw=0.8)
    ax.set_title(title, fontsize=9, color=INK); ax.set_xlabel('update')
axs.flat[0].legend(frameon=False)
fig.tight_layout(); fig.savefig(f'{args.out}/fig_dev_curves.png', dpi=160); plt.close(fig)

# ---- tables
CONDS = ['correct', 'complementary', 'mismatched', 'noimage']
o = ['# Task 2 results (generated by make_report.py)\n']
for k, fe in FE.items():
    o.append(f'\n## {k} visual tokens\n')
    for suite, res in fe.items():
        o.append(f"\n### {suite} ({res['n_pairs']} pairs, {2 * res['n_pairs']} questions)\n")
        o.append('| image condition | accuracy | pair accuracy | identical pair answers | empty | answer NLL | follows partner answer | s/answer |')
        o.append('|---|---|---|---|---|---|---|---|')
        ci = res['bootstrap_95ci']
        for c in CONDS:
            r = res[c]; a = ci[f'acc_{c}']
            o.append(f"| {c} | {100 * r['acc']:.1f} [{100 * a[0]:.1f}, {100 * a[1]:.1f}] | {100 * r['pair_acc']:.1f} | "
                     f"{100 * r['identical']:.1f} | {100 * r['empty']:.1f} | {r['nll']:.3f} | {100 * r['follows_partner']:.1f} | "
                     f"{r['gen_time_per_answer']:.3f} |")
        o.append('\nCorrect-image advantage (pair bootstrap, 4000 resamples, 95% CI):\n')
        o.append('| vs control | accuracy advantage (pts) | NLL advantage (nats) |')
        o.append('|---|---|---|')
        for c in CONDS[1:]:
            a, n = ci[f'adv_acc_vs_{c}'], ci[f'adv_nll_vs_{c}']
            o.append(f"| {c} | {100 * res['advantages'][f'adv_acc_vs_{c}']:+.1f} [{100 * a[0]:+.1f}, {100 * a[1]:+.1f}] | "
                     f"{res['advantages'][f'adv_nll_vs_{c}']:+.3f} [{n[0]:+.3f}, {n[1]:+.3f}] |")
        o.append('\nBy question type (accuracy % / pair accuracy %):\n')
        o.append('| type | ' + ' | '.join(CONDS) + ' |')
        o.append('|---' * (len(CONDS) + 1) + '|')
        for t, d in res['by_type'].items():
            o.append(f'| {t} | ' + ' | '.join(f"{100 * d[c]['acc']:.1f} / {100 * d[c]['pair_acc']:.1f}" for c in CONDS) + ' |')
# dev table at stage ends
o.append('\n## Development diagnostics at stage boundaries\n')
o.append('| run | update | stage | caption loss | grounding swap pen. | grounding no-image pen. | VQA swap pen. | VQA no-image pen. |')
o.append('|---|---|---|---|---|---|---|---|')
for k, dv in DV.items():
    for r in dv:
        if r['update'] in (0, 2250, 3750, 4500):
            o.append(f"| {k} | {r['update']} | {r['stage']} | {r['caption_ref_loss']:.3f} | {r['grounding_dev_swap_penalty']:+.3f} | "
                     f"{r['grounding_dev_noimage_penalty']:+.3f} | {r['vqa_dev_swap_penalty']:+.3f} | {r['vqa_dev_noimage_penalty']:+.3f} |")
# resources
o.append('\n## Resources\n')
o.append('| run | stage | updates | trainable params | wall time (min) | peak GPU mem (GiB) | mixture |')
o.append('|---|---|---|---|---|---|---|')
for k, s in SM.items():
    for st, d in s.get('stage_info', {}).items():
        if 'time_s' in d:
            o.append(f"| {k} | {st} | {d['updates']} | {d['trainable_params']:,} | {d['time_s'] / 60:.1f} | "
                     f"{d['peak_gpu_mem_bytes'] / 2**30:.2f} | {d.get('mixture_counts')} |")
    if 'final_eval_peak_gpu_mem_bytes' in s:
        o.append(f"| {k} | final eval | - | - | - | {s['final_eval_peak_gpu_mem_bytes'] / 2**30:.2f} | - |")
open(f'{args.out}/tables.md', 'w').write('\n'.join(o) + '\n')

# ---- qualitative examples (first run): seeded picks from success / failure categories
k0 = next(iter(RUNS))
rows = PE[k0]
q = ['# Qualitative examples (' + k0 + ' visual tokens; seeded selection, seed 6304)\n']
cats = {
    'Pair solved, swap flips the answer to the partner answer': lambda r: r['correct']['match'] and r['complementary']['follows_partner'],
    'Correct with the right image but unchanged under the complementary image': lambda r: r['correct']['match'] and r['complementary']['match'],
    'Wrong with the right image, answer equals the partner answer (language prior / insensitivity)': lambda r: (not r['correct']['match']) and r['correct']['follows_partner'],
    'Wrong with the right image, other error': lambda r: (not r['correct']['match']) and not r['correct']['follows_partner'],
}
rr = random.Random(6304)
for title, f in cats.items():
    for suite in ['grounding_test', 'vqa_test']:
        pool = [r for r in rows if r['suite'] == suite and f(r)]
        q.append(f'\n## {title} - {suite} ({len(pool)} of {sum(r["suite"] == suite for r in rows)} questions)\n')
        if not pool:
            continue
        q.append('| image id | question | reference | partner ref. | correct | complementary | mismatched | no image |')
        q.append('|---|---|---|---|---|---|---|---|')
        for r in rr.sample(pool, min(4, len(pool))):
            q.append(f"| {r['image_id']} | {r['question']} | {r['answer']} | {r['partner_answer']} | " +
                     ' | '.join(repr(r[c]['pred']) for c in CONDS) + ' |')
open(f'{args.out}/qualitative.md', 'w').write('\n'.join(q) + '\n')
print('wrote', os.listdir(args.out))
