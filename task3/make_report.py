"""Task 3 figures and tables from t3_offline.py (and optionally t3_live_eval.py) outputs.
Usage: python make_report.py --offline DIR [--live DIR] --out DIR
"""
import json, argparse, os
import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

ap = argparse.ArgumentParser()
ap.add_argument('--offline', required=True)
ap.add_argument('--live')
ap.add_argument('--out', required=True)
args = ap.parse_args()
os.makedirs(args.out, exist_ok=True)
COL = ['#2a78d6', '#eb6834', '#1baf7a', '#eda100', '#e87ba4', '#008300', '#6250d6', '#e34948']
INK, INK2 = '#0b0b0b', '#52514e'
plt.rcParams.update({'font.size': 9, 'axes.edgecolor': INK2, 'xtick.color': INK2, 'ytick.color': INK2,
                     'axes.spines.top': False, 'axes.spines.right': False, 'axes.grid': True,
                     'grid.color': '#e6e5e0', 'grid.linewidth': 0.6, 'lines.linewidth': 2})
NAMES = {'first': 'single rollout', 'sc': 'self-consistency', 'logp_highest': 'log-prob highest', 'logp_rwc': 'log-prob RWC',
         'selfcert_highest': 'self-certainty highest', 'selfcert_rwc': 'self-certainty RWC', 'shortest': 'shortest',
         'vision_highest': 'vision highest', 'vision_rwc': 'vision RWC', 'visconf_highest': 'VisConf highest',
         'visconf_rwc': 'VisConf RWC', 'visconf_tok_highest': 'token-fused highest', 'visconf_tok_rwc': 'token-fused RWC'}
R = {n: json.load(open(f'{args.offline}/{n}_results.json')) for n in ['math', 'mathvista']
     if os.path.exists(f'{args.offline}/{n}_results.json')}
o = ['# Task 3 results (generated by make_report.py)\n',
     'Held-out evaluation split (800 questions per dataset), accuracy averaged over 10 seeded rollout orders; '
     '95% CIs from 1,000 question-level bootstrap resamples.\n']

for name, res in R.items():
    E = res['splits']['eval']; Ns = res['budgets']; M = res['methods']
    main = ['first', 'sc', 'logp_rwc', 'selfcert_rwc', 'shortest'] + \
           (['vision_rwc', 'visconf_rwc', 'visconf_tok_rwc'] if name == 'mathvista' else [])
    # scaling curves: highest vs RWC panels
    fig, axs = plt.subplots(1, 2, figsize=(10, 3.6), sharey=True)
    for ax, kind in zip(axs, ['highest', 'rwc']):
        ax.plot(Ns, np.array(E['oracle']) * 100, color=INK2, ls='--', lw=1.2, label='oracle (any correct)')
        ms = ['first', 'sc'] + [m for m in M if m.endswith(kind)]
        for i, m in enumerate(ms):
            y = np.array(E['acc'][m]) * 100; ci = np.array(E['acc_ci95'][m]) * 100
            ax.plot(Ns, y, color=COL[i], marker='o', ms=4, label=NAMES[m])
            ax.fill_between(Ns, ci[0], ci[1], color=COL[i], alpha=0.12, lw=0)
        ax.set_xscale('log', base=2); ax.set_xticks(Ns); ax.set_xticklabels(Ns)
        ax.set_xlabel('rollouts N'); ax.set_title(f'{name}: {"highest-score" if kind == "highest" else "rank-weighted consistency"}', fontsize=9)
        ax.legend(frameon=False, fontsize=7)
    axs[0].set_ylabel('accuracy (%)')
    fig.tight_layout(); fig.savefig(f'{args.out}/{name}_scaling.png', dpi=160); plt.close(fig)
    # accuracy vs token cost
    fig, ax = plt.subplots(figsize=(5.5, 3.6))
    for i, m in enumerate(main):
        ax.plot(np.array(E['token_cost'][m]) / 1000, np.array(E['acc'][m]) * 100, color=COL[i], marker='o', ms=4, label=NAMES[m])
    ax.set_xscale('log'); ax.set_xlabel('mean generated tokens per question (thousands, log)'); ax.set_ylabel('accuracy (%)')
    ax.set_title(f'{name}: accuracy vs generation cost', fontsize=9); ax.legend(frameon=False, fontsize=7)
    fig.tight_layout(); fig.savefig(f'{args.out}/{name}_acc_vs_cost.png', dpi=160); plt.close(fig)

    o.append(f'\n## {name}\n')
    o.append('### Accuracy (%) by budget N, evaluation split\n')
    o.append('| method | ' + ' | '.join(f'N={n}' for n in Ns) + ' | N=32 95% CI | N=32 diff vs SC [95% CI] |')
    o.append('|---' * (len(Ns) + 3) + '|')
    o.append('| oracle | ' + ' | '.join(f'{100 * x:.1f}' for x in E['oracle']) + ' | - | - |')
    for m in M:
        ci = E['acc_ci95'][m]; d = E['diff_vs_sc_ci95'][m]
        diff = 100 * (E['acc'][m][-1] - E['acc']['sc'][-1])
        o.append(f'| {NAMES[m]} | ' + ' | '.join(f'{100 * x:.1f}' for x in E['acc'][m]) +
                 f' | [{100 * ci[0][-1]:.1f}, {100 * ci[1][-1]:.1f}] | {diff:+.1f} [{100 * d[0][-1]:+.1f}, {100 * d[1][-1]:+.1f}] |')
    o.append('\n### Failure decomposition (%, evaluation split)\n')
    o.append('| N | sampling failure (no correct rollout) | mean distinct answers | SC selection failure | best-RWC selection failure |')
    o.append('|---|---|---|---|---|')
    best = max([m for m in M if m.endswith('rwc')], key=lambda m: E['acc'][m][-1])
    for j, n in enumerate(Ns):
        o.append(f"| {n} | {100 * E['sampling_failure'][j]:.1f} | {E['distinct_groups'][j]:.2f} | "
                 f"{100 * E['selection_failure']['sc'][j]:.1f} | {100 * E['selection_failure'][best][j]:.1f} ({NAMES[best]}) |")
    o.append('\n### Mean generated tokens per question\n')
    o.append('| method | ' + ' | '.join(f'N={n}' for n in Ns) + ' |')
    o.append('|---' * (len(Ns) + 1) + '|')
    for m in ['first', 'sc']:
        o.append(f'| {NAMES[m]} | ' + ' | '.join(f'{x:.0f}' for x in E['token_cost'][m]) + ' |')
    o.append('\n### What the signals capture (N = 32, evaluation split)\n')
    S = res['signals_N32']['eval']
    o.append('| signal | top-8 minus bottom-8 accuracy (pts) | mean within-question Spearman with correctness | questions with mixed outcomes | Spearman with length |')
    o.append('|---|---|---|---|---|')
    for k, v in S.items():
        if isinstance(v, dict):
            sp = v['mean_within_q_spearman_with_correct']
            o.append(f"| {k} | {100 * v['top_minus_bottom_quartile_acc']:+.1f} | {sp if sp is None else round(sp, 3)} | "
                     f"{v['n_questions_mixed']} | {S.get('spearman_length_vs_' + k, float('nan')):.3f} |")
    if 'confidence_vision_within_rollout_corr' in res['signals_N32']:
        c = res['signals_N32']['confidence_vision_within_rollout_corr']
        o.append(f"\nWithin-rollout correlation between calibrated confidence and vision dependence (eval): mean {c['mean']:.3f}, "
                 f"median {c['median']:.3f}, 10th-90th pct [{c['q10']:.3f}, {c['q90']:.3f}], positive in {100 * c['frac_positive']:.1f}% of {c['n']} rollouts.\n")
    ad = res['adaptive']
    o.append('\n### Adaptive sampling (thresholds chosen on dev, applied to eval)\n')
    o.append('| policy | tau | gamma | eval accuracy (%) | mean rollouts | mean tokens | stop distribution | wrong early stops that N=32 fixes (%) |')
    o.append('|---|---|---|---|---|---|---|---|')
    for k, v in ad['eval'].items():
        sel = ad['selected'].get(k, {})
        o.append(f"| {k} | {sel.get('tau', '-')} | {sel.get('gamma', '-')} | {100 * v['acc']:.1f} | {v['mean_rollouts']:.1f} | "
                 f"{v['token_cost']:.0f} | {v['stop_dist']} | {100 * v['incorrect_early_stops_where_fixed32_correct']:.1f} |")
    # adaptive frontier on dev
    fig, ax = plt.subplots(figsize=(5.5, 3.6))
    for i, fam in enumerate(['agreement', 'quality_aware']):
        pts = [(v['token_cost'], v['acc']) for k, v in ad['grid'].items() if k.startswith(fam + '|')]
        ax.scatter([p[0] / 1000 for p in pts], [100 * p[1] for p in pts], color=COL[i], s=18, label=f'{fam} (dev grid)')
    f32 = ad['fixed32_dev']
    ax.scatter([f32['token_cost'] / 1000], [100 * f32['acc']], color=INK, marker='*', s=80, label='fixed N=32 SC (dev)')
    ax.set_xlabel('mean tokens per question (thousands)'); ax.set_ylabel('dev accuracy (%)')
    ax.set_title(f'{name}: adaptive stopping trade-off', fontsize=9); ax.legend(frameon=False, fontsize=7)
    fig.tight_layout(); fig.savefig(f'{args.out}/{name}_adaptive.png', dpi=160); plt.close(fig)

# trajectories
tp = f'{args.offline}/mathvista_trajectories.json'
if os.path.exists(tp):
    T = json.load(open(tp))[:6]
    fig, axs = plt.subplots(len(T) // 2, 2, figsize=(10, 2.2 * (len(T) // 2)), squeeze=False)
    for ax, t in zip(axs.flat, T):
        x = np.arange(len(t['c']))
        ax.plot(x, t['c'], color=COL[0], lw=1, label='calibrated confidence')
        ax.plot(x, t['v'], color=COL[1], lw=1, label='vision dependence')
        ax.set_title(f"{t['sample_id']} rollout {t['rollout']} ({t['tag']}, {'correct' if t['correct'] else 'wrong'})", fontsize=8)
        ax.set_xlabel('token', fontsize=8)
    axs.flat[0].legend(frameon=False, fontsize=7)
    fig.tight_layout(); fig.savefig(f'{args.out}/mathvista_trajectories.png', dpi=160); plt.close(fig)

if args.live and os.path.exists(f'{args.live}/live_results.json'):
    L = json.load(open(f'{args.live}/live_results.json'))['summary']
    o.append('\n## Live comparison (50 MATH eval questions, Qwen2.5-3B-Instruct, 3,072-token allowance)\n')
    o.append('| strategy | accuracy (%) | mean output tokens | mean input tokens | mean seconds | truncation (%) | extraction (%) |')
    o.append('|---|---|---|---|---|---|---|')
    for s in ['single', 'parallel', 'refinement']:
        d = L[s]
        o.append(f"| {s} | {100 * d['accuracy']:.1f} | {d['mean_output_tokens']:.0f} | {d['mean_input_tokens']:.0f} | "
                 f"{d['mean_seconds']:.1f} | {100 * d.get('truncation_rate', d.get('truncation_rate_revision', 0)):.1f} | "
                 f"{100 * d['extraction_rate']:.1f} |")
    r = L['refinement']
    o.append(f"\nRefinement: initial accuracy {100 * r['initial_accuracy']:.1f}%; wrong->correct {r['wrong_to_correct']}, "
             f"correct->wrong {r['correct_to_wrong']}, unchanged correct {r['unchanged_correct']}, unchanged wrong {r['unchanged_wrong']}; "
             f"initial truncation {100 * r['truncation_rate_initial']:.1f}%, mean critique tokens {r['mean_critique_tokens']:.0f}. "
             f"Parallel oracle (any of 3 correct): {100 * L['parallel']['oracle_any_of_3']:.1f}%. "
             f"GPU {L['gpu']}, peak memory {L['peak_gpu_mem_bytes'] / 2**30:.2f} GiB.\n")
open(f'{args.out}/tables.md', 'w').write('\n'.join(o) + '\n')
print('wrote', sorted(os.listdir(args.out)))
