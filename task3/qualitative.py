"""Task 3, Step 6: qualitative cases and stopping analysis from the saved offline/live outputs (no raw data needed).
Selection rules for illustrative examples (fixed before looking at the cases):
  * Selection disagreement: N = 32, rollout order 0, held-out evaluation questions in split order; the first 3 where
    self-consistency is correct and the best RWC rule is wrong, and the first 3 where the reverse holds.
  * Premature stopping: agreement controller with the development-selected tau, order 0, evaluation questions in split
    order; the first 4 where it stops early with a wrong answer although fixed-32 self-consistency is correct.
  * Revision: every wrong->correct and correct->wrong transition on the 50 live questions, plus the first 2 unchanged-
    wrong questions (live index order); parallel/single disagreements: the first 3 in each direction.
Usage: python qualitative.py --offline DIR --live DIR --out DIR
"""
import json, argparse, collections, re
import numpy as np
import pandas as pd

ap = argparse.ArgumentParser()
ap.add_argument('--offline', required=True)
ap.add_argument('--live', required=True)
ap.add_argument('--out', required=True)
args = ap.parse_args()
SEED, N_ORDERS, CHECK = 6304, 10, [4, 8, 16]
NO = 'NO_ANSWER'
SPL = json.load(open(f'{args.offline}/splits.json'))

from math_verify import parse as mv_parse, verify as mv_verify
_pc, _vc = {}, {}


def canon(s):
    s = str(s)
    for a, b in [('\\left', ''), ('\\right', ''), ('\\!', ''), ('\\,', ''), ('\\;', ''), ('\\dfrac', '\\frac'),
                 ('\\tfrac', '\\frac'), (' ', ''), ('\\%', '%')]:
        s = s.replace(a, b)
    return s.rstrip('.')


def mparse(s):
    if s not in _pc:
        try:
            _pc[s] = mv_parse('\\boxed{' + s + '}', parsing_timeout=2)
        except Exception:
            _pc[s] = []
    return _pc[s]


def mequal(a, b):  # identical to t3_offline.py
    if a == b or canon(a) == canon(b):
        return True
    if (a, b) not in _vc:
        pa, pb = mparse(a), mparse(b)
        try:
            _vc[(a, b)] = bool(pa) and bool(pb) and bool(mv_verify(pa, pb, timeout_seconds=2))
        except Exception:
            _vc[(a, b)] = False
    return _vc[(a, b)]


def groups(name, answers):
    reps, gid = [], []
    for a in answers:
        if a == NO:
            gid.append(-1); continue
        for j, r in enumerate(reps):
            if (mequal(r, a) if name == 'math' else r == a):
                gid.append(j); break
        else:
            reps.append(a); gid.append(len(reps) - 1)
    return np.array(gid), reps


def sc(g, P):
    seen = {}
    for pos, x in enumerate(g[P]):
        seen.setdefault(x, [0, pos])[0] += 1
    best = min(seen.items(), key=lambda kv: (-kv[1][0], kv[1][1]))
    return P[best[1][1]], best[1][0], best[0]


def md_cell(s, n=60):
    s = str(s).replace('|', '\\|').replace('\n', ' ')
    return s if len(s) <= n else s[:n] + '…'


out = ['# Task 3 qualitative cases and stopping analysis (generated by qualitative.py)\n',
       'Example-selection rules are stated in the docstring of `task3/qualitative.py` and repeated per section.\n']
stop_json = {}
for name, best_rwc in [('math', 'selfcert_rwc'), ('mathvista', 'visconf_rwc')]:
    L = json.load(open(f'{args.offline}/{name}_labels.json'))
    ids = [q['sample_id'] for q in L]
    assert ids == sorted(ids)
    lab = {q['sample_id']: q for q in L}
    rng = np.random.default_rng(SEED)
    orders = {sid: [rng.permutation(32) for _ in range(N_ORDERS)] for sid in ids}  # same draws as t3_offline.py
    ev = SPL[name]['eval']
    pq = pd.read_csv(f'{args.offline}/{name}_per_question.csv.gz', dtype={'sample_id': str, 'selected_rollouts': str})
    pq = pq[pq.N == 32].set_index(['sample_id', 'method'])
    res = json.load(open(f'{args.offline}/{name}_results.json'))
    tau = res['adaptive']['selected']['agreement']['tau']
    out.append(f'\n## {name}\n')
    # ---------------- selection disagreement
    G = {}
    for sid in ev:
        G[sid] = groups(name, lab[sid]['answers'])[0]
    cases = {'SC correct, RWC wrong': [], 'RWC correct, SC wrong': []}
    for sid in ev:
        corr = np.array(lab[sid]['correct'], bool)
        i_sc = int(str(pq.loc[(sid, 'sc'), 'selected_rollouts']).split()[0])
        i_rw = int(str(pq.loc[(sid, best_rwc), 'selected_rollouts']).split()[0])
        if corr[i_sc] and not corr[i_rw] and len(cases['SC correct, RWC wrong']) < 3:
            cases['SC correct, RWC wrong'].append((sid, i_sc, i_rw))
        if corr[i_rw] and not corr[i_sc] and len(cases['RWC correct, SC wrong']) < 3:
            cases['RWC correct, SC wrong'].append((sid, i_sc, i_rw))
    out.append(f'### Selection disagreement at N = 32 (order 0): self-consistency vs {best_rwc}\n')
    out.append('Rule: first 3 held-out questions (split order) in each direction.\n')
    out.append('| case | question | gold | SC answer (votes/32) | RWC answer (votes/32) | correct rollouts /32 | answer groups |')
    out.append('|---|---|---|---|---|---|---|')
    for k, lst in cases.items():
        for sid, i_sc, i_rw in lst:
            q = lab[sid]; g = G[sid]
            out.append(f"| {k} | {sid} | {md_cell(q['gold'], 25)} | {md_cell(q['answers'][i_sc], 25)} ({int((g == g[i_sc]).sum())}) | "
                       f"{md_cell(q['answers'][i_rw], 25)} ({int((g == g[i_rw]).sum())}) | {sum(q['correct'])} | {q['n_groups']} |")
    # ---------------- agreement-based stopping (selected tau): analysis + premature stops
    rows, prem = [], []
    for sid in ev:
        q = lab[sid]; g = G[sid]; corr = np.array(q['correct'], bool)
        for oi, o in enumerate(orders[sid]):
            stop = 32
            for n in CHECK:
                P = o[:n]
                cnt = collections.Counter(g[P].tolist()).most_common()
                unique = len(cnt) == 1 or cnt[0][1] > cnt[1][1]
                if unique and cnt[0][0] != -1 and cnt[0][1] / n >= tau:
                    stop = n; break
            i_stop, votes, _ = sc(g, o[:stop])
            i_32, _, _ = sc(g, o)
            rows.append(dict(stop=stop, share=votes / stop, correct=bool(corr[i_stop]), frac_correct=float(corr.mean()),
                             correct32=bool(corr[i_32])))
            if oi == 0 and stop < 32 and not corr[i_stop] and corr[i_32] and len(prem) < 4:
                prem.append((sid, stop, q['answers'][i_stop], votes, q['answers'][i_32], int(corr.sum()), q['gold']))
    df = pd.DataFrame(rows)
    df['fc_bin'] = pd.cut(df.frac_correct, [-0.01, 0.0, 0.25, 0.5, 0.75, 0.99, 1.0],
                          labels=['0', '(0,.25]', '(.25,.5]', '(.5,.75]', '(.75,1)', '1'])
    by_stop = df.groupby('stop').agg(n=('correct', 'size'), accuracy=('correct', 'mean'), fixed32_accuracy=('correct32', 'mean'),
                                     mean_lead_share=('share', 'mean'), mean_frac_correct_pool=('frac_correct', 'mean'))
    by_fc = df.groupby('fc_bin', observed=False).agg(n=('correct', 'size'), mean_stop=('stop', 'mean'),
                                                     early_stop_rate=('stop', lambda s: float((s < 32).mean())),
                                                     accuracy=('correct', 'mean'), fixed32_accuracy=('correct32', 'mean'))
    stop_json[name] = dict(tau=tau, by_stop=by_stop.reset_index().to_dict('records'),
                           by_fraction_correct=by_fc.reset_index().astype({'fc_bin': str}).to_dict('records'))
    out.append(f'\n### Agreement-based stopping (tau = {tau}, dev-selected), held-out split, all 10 orders\n')
    out.append('Stopping point vs. agreement and the (retrospective) fraction of correct rollouts in the full pool:\n')
    out.append('| stop at n | question-orders | accuracy | fixed-32 SC accuracy | mean leading-answer share | mean fraction correct in pool |')
    out.append('|---|---|---|---|---|---|')
    for s, r in by_stop.iterrows():
        out.append(f'| {s} | {int(r.n)} | {100 * r.accuracy:.1f} | {100 * r.fixed32_accuracy:.1f} | {r.mean_lead_share:.2f} | {r.mean_frac_correct_pool:.2f} |')
    out.append('\n| fraction of correct rollouts in pool | question-orders | early-stop rate | mean rollouts | accuracy | fixed-32 SC accuracy |')
    out.append('|---|---|---|---|---|---|')
    for b, r in by_fc.iterrows():
        if r.n:
            out.append(f'| {b} | {int(r.n)} | {100 * r.early_stop_rate:.1f} | {r.mean_stop:.1f} | {100 * r.accuracy:.1f} | {100 * r.fixed32_accuracy:.1f} |')
    out.append('\nPremature stops (rule: first 4 held-out questions, order 0, early wrong stop where fixed-32 SC is correct):\n')
    out.append('| question | stopped at n | answer at stop (votes) | fixed-32 SC answer | correct rollouts /32 | gold |')
    out.append('|---|---|---|---|---|---|')
    for sid, n, a, v, a32, nc, gold in prem:
        out.append(f'| {sid} | {n} | {md_cell(a, 25)} ({v}/{n}) | {md_cell(a32, 25)} | {nc} | {md_cell(gold, 25)} |')
    if not prem:
        out.append('| (none under this rule) | | | | | |')

# ---------------- live: revision and parallel vs single
LR = json.load(open(f'{args.live}/live_results.json'))['per_question']
raw = {}
for line in open(f'{args.live}/live_shard0.jsonl'):
    r = json.loads(line); raw[r['sample_id']] = r


def tail(s, n=220):
    s = re.sub(r'\s+', ' ', s).strip()
    return md_cell(s[-n:], n)


out.append('\n## Live MATH comparison (50 questions)\n')
out.append('### Sequential refinement transitions\n')
out.append('Rule: all wrong→correct and correct→wrong transitions, then the first 2 unchanged-wrong questions (live index order).\n')
out.append('| live idx | question | gold | initial answer | revised answer | transition | end of revision response |')
out.append('|---|---|---|---|---|---|---|')
sel = [q for q in LR if q['refinement']['initial_correct'] != q['refinement']['correct']]
sel += [q for q in LR if not q['refinement']['initial_correct'] and not q['refinement']['correct']][:2]
for q in sel:
    r = q['refinement']
    tr = ('wrong→correct' if r['correct'] else 'correct→wrong') if r['initial_correct'] != r['correct'] else 'unchanged wrong'
    qt = raw[q['sample_id']]['single']['prompt']
    qt = qt.split('<|im_start|>user\n')[-1].split('\n\nThink step by step')[0]
    out.append(f"| {q['live_index']} | {md_cell(qt, 70)} | {md_cell(q['gold'], 20)} | {md_cell(r['initial'], 20)} | "
               f"{md_cell(r['revised'], 20)} | {tr} | {tail(raw[q['sample_id']]['revision']['response'])} |")
out.append('\n### Single long response vs parallel self-consistency\n')
out.append('Rule: first 3 questions (live index order) in each direction.\n')
out.append('| live idx | gold | single answer (tokens, truncated) | parallel answers → selected | direction |')
out.append('|---|---|---|---|---|')
for cond, lab_ in [(lambda q: q['single']['correct'] and not q['parallel']['correct'], 'single correct, parallel wrong'),
                   (lambda q: q['parallel']['correct'] and not q['single']['correct'], 'parallel correct, single wrong')]:
    for q in [q for q in LR if cond(q)][:3]:
        s, p = q['single'], q['parallel']
        out.append(f"| {q['live_index']} | {md_cell(q['gold'], 20)} | {md_cell(s['answer'], 20)} ({s['out_tokens']}, {s['truncated']}) | "
                   f"{', '.join(md_cell(a, 15) for a in p['answers'])} → {md_cell(p['selected'], 15)} | {lab_} |")
open(f'{args.out}/qualitative.md', 'w').write('\n'.join(out) + '\n')
json.dump(stop_json, open(f'{args.out}/stopping_analysis.json', 'w'), indent=1, default=float)
print('wrote qualitative.md, stopping_analysis.json')
